// The real vinyl servers talk to haproxy over unix sockets in this directory.
// vinyld stats every backend .path when compiling VCL and complains if it is
// missing ("Cannot stat", a warning) or not a socket ("Not a socket", an
// error), so we create dummy socket files for the paths a submitted VCL uses.
// The Dockerfile makes sure the directory exists and is writable for us.
const (
	socketDirPath    = "/haproxy-unix-sockets"
	maxSocketsPerVCL = 32
)

var (
	// socketNameRe limits socket file names to a conservative character
	// set. It covers the haproxy_<origin group>_<http|https> names generated
	// by sunet-cdn-manager, where origin group names are DNS labels.
	socketNameRe = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,127}$`)

	// backendPathRe finds backend .path attributes laid out exactly the
	// way sunet-cdn-manager generates them in vcl-preamble.vcl: a whole
	// line holding a basic "..." string, with any indentation:
	//
	//	  .path = "/haproxy-unix-sockets/haproxy_default_https";
	//
	// Nothing legitimate writes a .path any other way, so other ways the
	// VCL lexer accepts, e.g. a backend on one line, different spacing,
	// "long strings" ({"..."} or """...""", see "Strings" in vcl(7):
	// https://vinyl-cache.org/docs/9.1/reference/vcl.html#strings) or
	// comments between tokens, are deliberately not recognized. Such a
	// .path gets no socket, so either vinyld complains about it (see
	// backendPathWarnings) or, if it resolves to a socket we created
	// anyway, checkCompiledBackendPaths finds that it is not one of the
	// recognized paths. The exception is the exact same path string also
	// written in the recognized layout elsewhere in the VCL, which is
	// allowed since it refers to the same socket.
	backendPathRe = regexp.MustCompile(`(?m)^[ \t]*\.path = "([^"\n]+)";$`)

	// backendPathWarningRe matches the start of a vinyld complaint about
	// a backend .path.
	backendPathWarningRe = regexp.MustCompile(`(?m)^Backend path: `)

	// compiledBackendPathRe finds the lines in the C code generated by
	// vinyld that set the unix socket path of a backend, which vinyld
	// writes like this:
	//
	//	.uds_path = "/haproxy-unix-sockets/haproxy_default_https",
	//
	// It deliberately matches any layout of such a line so one we do not
	// expect gets the VCL rejected instead of being overlooked. The VCL
	// source embedded in the C code is not matched since each of its lines
	// is a quoted C string.
	compiledBackendPathRe = regexp.MustCompile(`(?m)^[ \t]*\.uds_path\b.*$`)
)

// socketNamesFromVCL returns the unique socket file names that the VCL's
// backend .path attributes refer to, in first-seen order. All paths are
// untrusted: any path that is not a socket name directly inside
// socketDirPath, or more than maxSocketsPerVCL unique names, is an error.
// The error message is meant for the user who submitted the VCL.
func socketNamesFromVCL(vcl []byte) ([]string, error) {
	var names []string
	seen := map[string]bool{}

	for _, m := range backendPathRe.FindAllSubmatch(vcl, -1) {
		name, err := socketNameFromPath(string(m[1]))
		if err != nil {
			return nil, err
		}

		if seen[name] {
			continue
		}
		seen[name] = true
		names = append(names, name)

		if len(names) > maxSocketsPerVCL {
			return nil, fmt.Errorf("too many backend socket paths: at most %d unique paths are allowed", maxSocketsPerVCL)
		}
	}

	return names, nil
}

// socketNameFromPath returns the socket file name for a backend path, or an
// error meant for the user if the path is not a socket name directly inside
// socketDirPath.
func socketNameFromPath(path string) (string, error) {
	// filepath.Clean treats ".." as removing the component before it in
	// the text, while the kernel follows symlinks and then goes to the
	// parent of their target. If /proc/self/cwd points to
	// /var/lib/vinyl/data, then "/proc/self/cwd/../../../haproxy-unix-sockets/x"
	// cleans to "/haproxy-unix-sockets/x" but the kernel resolves it to
	// "/var/haproxy-unix-sockets/x". So "." and ".." are rejected, leaving
	// only redundant slashes for Clean to remove, where the two agree.
	for component := range strings.SplitSeq(path, "/") {
		if component == "." || component == ".." {
			return "", fmt.Errorf("backend path %q not allowed: must not contain \".\" or \"..\" path components", path)
		}
	}

	clean := filepath.Clean(path)
	name := filepath.Base(clean)
	if filepath.Dir(clean) != socketDirPath || !socketNameRe.MatchString(name) {
		return "", fmt.Errorf("backend path %q not allowed: must be a file directly in %s with a name matching %s", path, socketDirPath, socketNameRe)
	}
	return name, nil
}

// checkCompiledBackendPaths compares the backend paths vinyld compiled, as
// found in its generated C code, with the paths socketNamesFromVCL recognized
// in the VCL. A path written in a way the scan does not recognize can still
// compile without complaints if it resolves to a socket we created, e.g.
// {"/proc/self/root/haproxy-unix-sockets/..."} or a socket held by another
// request, so every compiled path must be exactly a recognized one. Every
// recognized path must also be compiled, which makes the check fail loudly
// instead of silently passing if vinyld changes its C code.
func checkCompiledBackendPaths(vcl []byte, cCode string) error {
	expected := map[string]bool{}
	var recognized []string
	for _, m := range backendPathRe.FindAllSubmatch(vcl, -1) {
		path := string(m[1])
		if !expected[path] {
			expected[path] = true
			recognized = append(recognized, path)
		}
	}

	compiled := map[string]bool{}
	for _, line := range compiledBackendPathRe.FindAllString(cCode, -1) {
		path, ok := strings.CutPrefix(line, "\t.uds_path = \"")
		if ok {
			path, ok = strings.CutSuffix(path, "\",")
		}
		if !ok {
			// Not the layout vinyld uses, so this is about vinyld
			// output we do not understand rather than how the VCL
			// was written.
			return fmt.Errorf("unexpected backend path line in vinyld output: %q", line)
		}
		if !expected[path] {
			// Point out a path that is not allowed however it is
			// written, otherwise say how to write it.
			name, err := socketNameFromPath(path)
			if err != nil {
				return err
			}
			return fmt.Errorf("backend path %q must be written as a line of its own in a backend: .path = \"%s/%s\";", path, socketDirPath, name)
		}
		compiled[path] = true
	}

	for _, path := range recognized {
		if !compiled[path] {
			return fmt.Errorf("backend path %q is not used by a backend: '.path = \"...\";' lines are only allowed in backend definitions", path)
		}
	}

	return nil
}

// backendPathWarnings returns the "Backend path:" complaints from vinyld
// output, each with its location, source line and marker line, or an empty
// string if there are none. Other output such as generated C code is left
// out since it is not meant for the user.
func backendPathWarnings(output string) string {
	var b strings.Builder
	inBlock := false

	for line := range strings.Lines(output) {
		if backendPathWarningRe.MatchString(line) {
			inBlock = true
		}
		if !inBlock {
			continue
		}
		b.WriteString(line)
		// Each complaint is followed by an empty line and then
		// "(That was just a warning)", which we leave out since we
		// treat it as an error.
		if strings.TrimSpace(line) == "" {
			inBlock = false
		}
	}

	return b.String()
}

// socketDir creates and removes dummy socket files in one directory. The
// directory is opened once and every later operation is relative to that
// handle, so replacing the directory path afterwards (for example with a
// symlink) does not change where files end up. Sockets are reference counted
// so concurrent requests using the same name share one file which is only
// removed when the last of them is done.
type socketDir struct {
	logger zerolog.Logger
	root   *os.Root
	// dir is the root directory opened as a file. os.Root has no Mknod
	// so we need a directory file descriptor for mknodSocketAt.
	dir *os.File

	mu   sync.Mutex
	refs map[string]int
}

// openSocketDir opens the directory at path and removes any socket files
// left in it, for example by an earlier run that crashed mid-request.
func openSocketDir(path string, logger zerolog.Logger) (*socketDir, error) {
	root, err := os.OpenRoot(path)
	if err != nil {
		return nil, err
	}

	s, err := newSocketDir(root, logger)
	if err != nil {
		_ = root.Close()
		return nil, err
	}

	err = s.removeLeftoverSockets()
	if err != nil {
		s.close()
		return nil, err
	}

	return s, nil
}

func newSocketDir(root *os.Root, logger zerolog.Logger) (*socketDir, error) {
	dir, err := root.Open(".")
	if err != nil {
		return nil, err
	}

	return &socketDir{
		logger: logger,
		root:   root,
		dir:    dir,
		refs:   map[string]int{},
	}, nil
}

func (s *socketDir) close() {
	_ = s.dir.Close()
	_ = s.root.Close()
}

func (s *socketDir) removeLeftoverSockets() error {
	entries, err := fs.ReadDir(s.root.FS(), ".")
	if err != nil {
		return err
	}

	for _, entry := range entries {
		if entry.Type() != fs.ModeSocket {
			continue
		}
		err := s.root.Remove(entry.Name())
		if err != nil {
			return err
		}
	}

	return nil
}

// isSafeName is a last line of defence on top of the stricter checks in
// socketNamesFromVCL: a single path component can not escape the directory
// when used with Mknodat or os.Root.
func isSafeName(name string) bool {
	return name != "" && name != "." && name != ".." && !strings.ContainsAny(name, "/\x00")
}

// acquire makes sure a socket file exists for each name until the returned
// release function is called. On error nothing is held.
func (s *socketDir) acquire(names []string) (func(), error) {
	for _, name := range names {
		if !isSafeName(name) {
			return nil, fmt.Errorf("unsafe socket name %q", name)
		}
	}

	s.mu.Lock()
	defer s.mu.Unlock()

	held := make([]string, 0, len(names))
	for _, name := range names {
		if s.refs[name] == 0 {
			err := s.create(name)
			if err != nil {
				s.releaseLocked(held)
				return nil, err
			}
		}
		s.refs[name]++
		held = append(held, name)
	}

	var once sync.Once
	release := func() {
		once.Do(func() {
			s.mu.Lock()
			defer s.mu.Unlock()
			s.releaseLocked(held)
		})
	}

	return release, nil
}

// create makes a socket file entry. We only need something that looks like a
// socket to vinyld, not a listening socket, so mknod is enough. An existing
// socket is fine (left over from a crash, it will be removed on release),
// anything else in the way is an error.
func (s *socketDir) create(name string) error {
	err := mknodSocketAt(s.dir, name)
	if err == nil {
		return nil
	}
	if !errors.Is(err, fs.ErrExist) {
		return fmt.Errorf("unable to create socket %q: %w", name, err)
	}

	fi, err := s.root.Lstat(name)
	if err != nil {
		return fmt.Errorf("unable to stat existing socket %q: %w", name, err)
	}
	if fi.Mode().Type() != fs.ModeSocket {
		return fmt.Errorf("existing file %q is not a socket", name)
	}

	return nil
}

// releaseLocked must be called with s.mu held.
func (s *socketDir) releaseLocked(names []string) {
	for _, name := range names {
		s.refs[name]--
		if s.refs[name] > 0 {
			continue
		}
		delete(s.refs, name)
		err := s.root.Remove(name)
		if err != nil {
			s.logger.Err(err).Str("socket", name).Msg("unable to remove socket")
		}
	}
}
